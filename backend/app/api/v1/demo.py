@router.get(
    "/sample-images/{sample_id}",
    summary="Download or Preview a Sample Image by ID",
    description="Returns the binary image content for the requested sample ID."
)
async def get_sample_image_file(sample_id: str):
    """Streams the requested sample image."""
    from fastapi.responses import FileResponse
    import os

    samples_map = {
        "sample-clean": "dataset/Faulty_solar_panel/Clean/Clean (1).jpeg",
        "sample-dusty": "dataset/Faulty_solar_panel/Dusty/Dust (1).jpg",
        "sample-bird-drop": "dataset/Faulty_solar_panel/Bird-drop/Bird (1).jpeg",
        "sample-snow-covered": "dataset/Faulty_solar_panel/Snow-Covered/Snow (1).jpg",
        "sample-electrical-damage": "dataset/Faulty_solar_panel/Electrical-damage/Electrical (1).jpg",
        "sample-physical-damage": "dataset/Faulty_solar_panel/Physical-Damage/Physical (1).jpg",
    }

    if sample_id not in samples_map:
        raise HTTPException(status_code=404, detail=f"Sample image '{sample_id}' not found.")

    rel_path = samples_map[sample_id]
    if not os.path.exists(rel_path):
        raise HTTPException(status_code=404, detail=f"Sample file '{rel_path}' does not exist on disk.")

    media_type = "image/jpeg" if rel_path.lower().endswith((".jpg", ".jpeg")) else "image/png"
    return FileResponse(rel_path, media_type=media_type)


