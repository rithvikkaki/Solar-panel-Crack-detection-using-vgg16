"""
SolarSentinel AI - Demo Mode & Capability Reporting API
"""

from fastapi import APIRouter, Depends, File, HTTPException, UploadFile, status

from backend.app.dependencies import get_model_service
from backend.app.schemas.health import DemoStatusResponse
from backend.app.schemas.inspection import InspectionResponse
from backend.app.services.inspection_service import ImageValidationError, InspectionService
from backend.app.services.model_service import ModelService

router = APIRouter(prefix="/demo", tags=["Demo Visualization"])


@router.get(
    "/status",
    response_model=DemoStatusResponse,
    summary="Get Current Application Operation Mode",
    description="Reports whether backend is operating in REAL_MODEL mode or DEMO_ONLY mode."
)
async def get_demo_status(ms: ModelService = Depends(get_model_service)) -> DemoStatusResponse:
    if ms.is_loaded:
        return DemoStatusResponse(
            mode="REAL_MODEL",
            model_available=True,
            message="Active neural network weights are loaded. Full production inference and Grad-CAM are operational."
        )
    else:
        return DemoStatusResponse(
            mode="DEMO_ONLY",
            model_available=False,
            message=(
                "Trained weights are not currently present on disk. "
                "The application is operating in DEMO_ONLY mode. "
                "No synthetic predictions will be returned by the standard /inspect endpoint."
            ),
            setup_instructions=[
                "1. Place raw solar panel images into `data/raw/` organized by class directory.",
                "2. Validate dataset: `python ml/training/validate_dataset.py --data_dir data/raw`",
                "3. Train model: `python ml/training/train.py --data_dir data/raw`",
                "4. Restart the backend to automatically load `ml/models/solar_sentinel_vgg16.keras`."
            ]
        )


@router.post(
    "/inspect",
    response_model=InspectionResponse,
    summary="Generate Illustrative Demo Visualization (Clearly Labeled)",
    description=(
        "Generates an illustrative UI preview of an inspection report. "
        "Strictly labeled: 'DEMO VISUALIZATION: Results are NOT generated by the trained neural network.' "
        "Allows full UI testing without fabricating model metrics."
    )
)
async def inspect_demo_preview(
    file: UploadFile = File(..., description="Sample solar panel image")
) -> InspectionResponse:
    try:
        file_bytes = await file.read()
        return InspectionService.process_demo_preview(
            file_bytes=file_bytes,
            filename=file.filename or "demo_sample.jpg"
        )
    except ImageValidationError as e:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=str(e)
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Demo preview error: {str(e)}"
        )


